-- PostgreSQL schema for the calendar assistant MVP.
-- Create the database separately (for example, calendar_assistant), then run this file in it.

CREATE TABLE IF NOT EXISTS screenshots (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type         TEXT NOT NULL CHECK (source_type IN ('plan', 'fact')),
    day_date            DATE NOT NULL,
    sent_at             TIMESTAMPTZ NOT NULL,
    telegram_file_id    TEXT,
    device_type         TEXT CHECK (device_type IN ('phone', 'desktop', 'unknown')),
    visible_from        TIME,
    visible_to          TIME,
    covers_full_day     BOOLEAN NOT NULL DEFAULT FALSE,
    date_confirmed      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (visible_from IS NULL OR (visible_from >= TIME '00:00' AND visible_from <= TIME '23:59')),
    CHECK (visible_to IS NULL OR (visible_to >= TIME '00:00' AND visible_to <= TIME '23:59'))
);

CREATE TABLE IF NOT EXISTS events (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screenshot_id           BIGINT NOT NULL REFERENCES screenshots(id) ON DELETE CASCADE,
    day_date                DATE NOT NULL,
    source_type             TEXT NOT NULL CHECK (source_type IN ('plan', 'fact')),
    task_name_raw           TEXT NOT NULL,
    task_name_normalized    TEXT NOT NULL,
    start_time              TIME,
    end_time                TIME,
    duration_minutes        INTEGER CHECK (duration_minutes IS NULL OR duration_minutes >= 0),
    label                   TEXT,
    color_hex               TEXT CHECK (color_hex IS NULL OR color_hex ~ '^#[0-9A-Fa-f]{6}$'),
    project_or_category     TEXT,
    visual_completion       TEXT NOT NULL DEFAULT 'unknown'
                            CHECK (visual_completion IN ('done', 'not_done', 'unknown')),
    recognition_confidence  REAL CHECK (
                                recognition_confidence IS NULL
                                OR (recognition_confidence >= 0.0 AND recognition_confidence <= 1.0)
                            ),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- MVP assumption: names are unique within one day and one source set.
-- Application normalization: Unicode NFC, trim, collapse whitespace, casefold.
CREATE UNIQUE INDEX IF NOT EXISTS uq_events_day_source_title
    ON events(day_date, source_type, task_name_normalized);

CREATE INDEX IF NOT EXISTS ix_events_day_source
    ON events(day_date, source_type);

CREATE TABLE IF NOT EXISTS event_matches (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_date            DATE NOT NULL,
    plan_event_id       BIGINT UNIQUE REFERENCES events(id) ON DELETE CASCADE,
    fact_event_id       BIGINT UNIQUE REFERENCES events(id) ON DELETE CASCADE,
    result              TEXT NOT NULL CHECK (
                            result IN ('done', 'partially_done', 'not_done',
                                       'outside_plan', 'unconfirmed', 'uncertain')
                        ),
    match_method        TEXT CHECK (match_method IS NULL OR match_method = 'exact_normalized_title'),
    reason              TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (plan_event_id IS NOT NULL OR fact_event_id IS NOT NULL),
    CHECK (
        (result IN ('done', 'partially_done') AND plan_event_id IS NOT NULL AND fact_event_id IS NOT NULL)
        OR (result IN ('not_done', 'unconfirmed') AND plan_event_id IS NOT NULL AND fact_event_id IS NULL)
        OR (result = 'outside_plan' AND plan_event_id IS NULL AND fact_event_id IS NOT NULL)
        OR result = 'uncertain'
    )
);

CREATE INDEX IF NOT EXISTS ix_matches_day_result
    ON event_matches(day_date, result);

CREATE OR REPLACE FUNCTION validate_event_screenshot()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM screenshots s
        WHERE s.id = NEW.screenshot_id
          AND s.day_date = NEW.day_date
          AND s.source_type = NEW.source_type
    ) THEN
        RAISE EXCEPTION 'event must match screenshot date and source_type';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_events_validate_screenshot ON events;
CREATE TRIGGER trg_events_validate_screenshot
BEFORE INSERT OR UPDATE OF screenshot_id, day_date, source_type ON events
FOR EACH ROW EXECUTE FUNCTION validate_event_screenshot();

CREATE OR REPLACE FUNCTION validate_event_match()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.plan_event_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM events e
        WHERE e.id = NEW.plan_event_id AND e.source_type = 'plan' AND e.day_date = NEW.day_date
    ) THEN
        RAISE EXCEPTION 'plan_event_id must reference a plan event on day_date';
    END IF;
    IF NEW.fact_event_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM events e
        WHERE e.id = NEW.fact_event_id AND e.source_type = 'fact' AND e.day_date = NEW.day_date
    ) THEN
        RAISE EXCEPTION 'fact_event_id must reference a fact event on day_date';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_event_matches_validate ON event_matches;
CREATE TRIGGER trg_event_matches_validate
BEFORE INSERT OR UPDATE OF day_date, plan_event_id, fact_event_id ON event_matches
FOR EACH ROW EXECUTE FUNCTION validate_event_match();
